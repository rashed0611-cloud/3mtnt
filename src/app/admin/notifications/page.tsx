import type { Metadata } from "next";
import Link from "next/link";
import { Bell, CircleAlert, Info, TriangleAlert } from "lucide-react";
import { Badge } from "@/components/ui/badge";
import { Card } from "@/components/ui/card";
import { PageHeader } from "@/components/ui/page-header";
import { requireUser } from "@/lib/auth";
import { getRepository } from "@/lib/db";
import { formatDateTime, titleCase } from "@/lib/utils";

export const metadata: Metadata = { title: "Notifications" };

export default async function NotificationsPage() {
  await requireUser();
  const activities = (await getRepository().getActivities()).slice(0, 20);
  const unread = activities.filter((activity) => activity.severity !== "info").length;

  return (
    <div className="space-y-4">
      <PageHeader
        title="Notifications"
        description="Operational alerts generated by bookings, payments, documents and account activity."
        breadcrumb={[{ label: "Workspace", href: "/admin" }, { label: "Notifications" }]}
        actions={<Badge tone="blue">{unread} requiring attention</Badge>}
      />

      <div className="grid gap-4 lg:grid-cols-[minmax(0,1fr)_300px]">
        <Card>
          <div className="flex items-center justify-between border-b border-line px-4 py-3">
            <h2 className="text-sm font-semibold text-ink">Inbox</h2>
            <span className="text-[10.5px] text-muted">{activities.length} notifications</span>
          </div>
          <div className="divide-y divide-line">
            {activities.map((activity) => {
              const Icon = activity.severity === "critical" ? CircleAlert : activity.severity === "warning" ? TriangleAlert : Info;
              return (
                <div key={activity.id} className="flex gap-3 px-4 py-3 hover:bg-slate-50/70">
                  <span
                    className={`mt-0.5 flex h-7 w-7 shrink-0 items-center justify-center rounded-full ${
                      activity.severity === "critical" ? "bg-red-50 text-red-600" : activity.severity === "warning" ? "bg-amber-50 text-amber-600" : "bg-blue-50 text-blue-600"
                    }`}
                  >
                    <Icon className="h-3.5 w-3.5" />
                  </span>
                  <div className="min-w-0 flex-1">
                    <div className="flex flex-wrap items-center gap-1.5">
                      <p className="text-[12px] font-medium text-ink">{titleCase(activity.action)}</p>
                      <Badge tone="neutral">{activity.module}</Badge>
                    </div>
                    <p className="mt-0.5 text-[11.5px] leading-5 text-slate-600">{activity.description}</p>
                    <p className="mt-0.5 text-[10px] text-slate-400">{formatDateTime(activity.createdAt)} · {activity.actor}</p>
                  </div>
                </div>
              );
            })}
          </div>
        </Card>

        <div className="space-y-4">
          <Card className="p-4">
            <div className="flex items-center gap-2">
              <Bell className="h-4 w-4 text-primary" />
              <p className="text-[12px] font-semibold text-ink">Notification preferences</p>
            </div>
            <div className="mt-3 space-y-2">
              {[
                ["Booking status changes", true],
                ["Payments & refunds", true],
                ["Document reminders", true],
                ["Supplier confirmations", true],
                ["Marketing digest", false],
              ].map(([label, enabled]) => (
                <label key={String(label)} className="flex items-center justify-between gap-2 text-[11.5px] text-slate-600">
                  {label}
                  <input type="checkbox" defaultChecked={Boolean(enabled)} className="h-3.5 w-3.5 rounded border-slate-300 text-primary focus:ring-primary/30" />
                </label>
              ))}
            </div>
          </Card>
          <Link href="/admin/activity-logs" className="block rounded-card border border-dashed border-slate-300 bg-white/60 p-3.5 text-[11.5px] font-medium text-slate-600 hover:border-primary/40 hover:text-primary">
            View the full audit trail →
          </Link>
        </div>
      </div>
    </div>
  );
}
